"""Dining page, separate daily tracker and storage acceptance checks."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
BASE = os.environ.get('BLB_TEST_URL', 'http://127.0.0.1:8000/Betterlunchbreaks/')
ARTIFACTS = Path(os.environ.get('BLB_ARTIFACTS', '/tmp/blb-test-artifacts')); ARTIFACTS.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    for label, width in [('desktop', 1440), ('phone', 390), ('narrow', 320)]:
        context = browser.new_context(viewport={'width':width,'height':900}, accept_downloads=True)
        page = context.new_page(); errors=[]
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto(BASE)
        expect(page.locator('#wait-count')).to_have_text('7')
        expect(page.locator('#open-count')).to_have_text('50–70')
        expect(page.locator('#purchase-form')).to_have_count(0)
        assert 'live' not in page.locator('body').inner_text().lower()
        assert page.locator('#rush-chart [role=listitem]').count() == 8
        page.locator('#scenario').select_option('rush'); expect(page.locator('#wait-count')).to_have_text('16')
        page.locator('#scenario').select_option('quiet'); expect(page.locator('#wait-count')).to_have_text('3')
        page.locator('#scenario').select_option('lunch')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(ARTIFACTS/f'{label}-dining.png'), full_page=True)
        page.locator('.page-nav').get_by_role('link', name='Dining Dollars').click()
        assert page.url.endswith('/dollars.html')
        expect(page.locator('#hall-title')).to_have_count(0)
        expect(page.locator('#budget-empty')).to_be_visible()
        page.get_by_role('button', name='Set up budget', exact=True).click()
        page.locator('#start').fill('2026-11-09'); page.locator('#end').fill('2026-11-13')
        page.locator('#starting').fill('400'); page.locator('#reserve').fill('50')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#daily')).to_have_text('$90.00')
        expect(page.locator('#balance')).to_have_text('$400.00')
        expect(page.locator('#view-settings')).to_be_hidden()
        page.locator('.tracker-nav').get_by_role('button', name='Log purchase', exact=True).click()
        page.get_by_role('button', name='$12', exact=True).click(); page.locator('#note').fill('Lunch at The Edge')
        page.locator('#log-purchase').click()
        page.locator('.tracker-nav').get_by_role('button', name='Overview', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$388.00')
        expect(page.locator('#daily')).to_have_text('$90.00')
        page.reload(); expect(page.locator('#balance')).to_have_text('$388.00')
        other=context.new_page(); other.goto(BASE+'dollars.html')
        expect(other.locator('#balance')).to_have_text('$388.00')
        page.locator('.tracker-nav').get_by_role('button', name='Settings', exact=True).click()
        page.locator('#holidays').fill('2026-11-11')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#daily')).to_have_text('$112.50')
        page.locator('.tracker-nav').get_by_role('button', name='Activity', exact=True).click()
        with page.expect_download() as info: page.get_by_role('button', name='Export CSV').click()
        assert 'Lunch at The Edge' in Path(info.value.path()).read_text()
        page.get_by_role('button', name='Remove Lunch at The Edge $12.00', exact=True).click()
        expect(other.locator('#balance')).to_have_text('$400.00')
        page.locator('.tracker-nav').get_by_role('button', name='Settings', exact=True).click()
        page.locator('#holidays').fill('wrong')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#budget-status')).to_contain_text('Check skipped dates')
        page.locator('#holidays').fill('2026-11-11'); page.locator('#day-override').fill('2')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#daily')).to_have_text('$225.00')
        page.locator('.tracker-nav').get_by_role('button', name='Log purchase', exact=True).click()
        page.locator('#amount').fill('500'); page.locator('#log-purchase').click()
        expect(page.locator('#budget-status')).to_contain_text('within your remaining balance')
        page.locator('#amount').fill('0.10'); page.locator('#note').fill('<img src=x onerror=alert(1)>'); page.locator('#log-purchase').click()
        page.locator('.tracker-nav').get_by_role('button', name='Activity', exact=True).click()
        assert not page.locator('#history img').count()
        expect(page.locator('#history')).to_contain_text('<img src=x onerror=alert(1)>')
        for view in ['settings','log','activity','overview']:
            page.locator(f'.tracker-nav [data-view={view}]').click()
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), view
        page.locator('h1').click(); page.screenshot(path=str(ARTIFACTS/f'{label}-daily-tracker.png'), full_page=True)
        page.locator('.page-nav').get_by_role('link', name='Dining', exact=True).click()
        expect(page.locator('#hall-title')).to_have_text('The Edge')
        assert not errors, errors
        print(f'PASS {label}: separate pages/navigation, sample dining/forecast/chart, tracker tabs, daily accrual, holidays/override, purchases/cents, persistence, tab sync, CSV, invalid inputs, safe notes, no overflow/errors')
        context.close()
    context=browser.new_context(); context.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw Error('blocked')}})")
    page=context.new_page(); page.goto(BASE+'dollars.html'); page.get_by_role('button', name='Set up budget', exact=True).click(); page.get_by_role('button', name='Save budget', exact=True).click()
    expect(page.locator('#budget-status')).to_contain_text('will be lost after a refresh')
    expect(page.locator('#balance')).to_have_text('$500.00'); context.close()
    context=browser.new_context(); page=context.new_page(); page.goto(BASE+'dollars.html'); page.evaluate("localStorage.setItem('better-lunch-budget-v2','{broken')"); page.reload()
    expect(page.locator('#budget-status')).to_contain_text('could not be read')
    page.keyboard.press('Tab'); expect(page.locator('.skip')).to_be_focused()
    print('PASS storage failure/corruption and keyboard skip link')
    print('Browser:',browser.version); browser.close()
