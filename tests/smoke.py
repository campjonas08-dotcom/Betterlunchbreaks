"""Acceptance checks for scan estimates and browser-local Dining Dollars."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('BLB_TEST_URL', 'http://127.0.0.1:8000/Betterlunchbreaks/')
ARTIFACTS = Path(os.environ.get('BLB_ARTIFACTS', '/tmp/blb-test-artifacts'))
ARTIFACTS.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    for label, width in [('desktop', 1440), ('phone', 390), ('narrow', 320)]:
        context = browser.new_context(viewport={'width': width, 'height': 900}, accept_downloads=True)
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(BASE)
        expect(page.locator('#wait-count')).to_have_text('0')
        expect(page.locator('#open-count')).to_have_text('170–200')
        expect(page.locator('#budget-empty')).to_be_visible()
        expect(page.locator('#log-purchase')).to_be_disabled()
        assert not page.locator('dialog, #tables, #checkout').count()
        text = page.locator('body').inner_text().lower()
        for removed in ['the village', 'prototype', 'demo', 'early access']:
            assert removed not in text
        page.locator('#scenario').select_option('rush')
        expect(page.locator('#wait-count')).to_have_text('4')
        expect(page.locator('#open-count')).to_have_text('Near capacity')
        expect(page.locator('#recommendation-title')).to_contain_text('to go')
        assert page.locator('#forecast > div').count() == 3
        page.locator('.assumptions summary').click()
        page.locator('#entries').fill('10'); page.locator('#exits').fill('11')
        page.get_by_role('button', name='Calculate from scans').click()
        expect(page.locator('#scan-status')).to_contain_text('no greater')
        page.locator('#entries').fill('324'); page.locator('#exits').fill('0')
        page.get_by_role('button', name='Calculate from scans').click()
        expect(page.locator('#wait-count')).to_have_text('1')
        page.locator('#entries').fill('0')
        page.get_by_role('button', name='Calculate from scans').click()
        expect(page.locator('#wait-count')).to_have_text('0')
        page.locator('#scenario').select_option('lunch')
        page.locator('.assumptions summary').click()
        # Explicit dates make the balance/weekday check reproducible.
        page.locator('#total').fill('500'); page.locator('#starting').fill('500')
        page.locator('#reserve').fill('50')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$500.00')
        expect(page.locator('#budget-empty')).to_be_hidden()
        expect(page.locator('#daily')).not_to_have_text('$0.00')
        page.get_by_role('button', name='$12', exact=True).click()
        page.locator('#note').fill('Lunch at The Edge')
        page.get_by_role('button', name='Log purchase', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$488.00')
        expect(page.locator('#history')).to_contain_text('Lunch at The Edge')
        page.reload()
        expect(page.locator('#balance')).to_have_text('$488.00')
        other = context.new_page(); other.goto(BASE)
        expect(other.locator('#balance')).to_have_text('$488.00')
        page.locator('#amount').fill('500')
        page.get_by_role('button', name='Log purchase', exact=True).click()
        expect(page.locator('#budget-status')).to_contain_text('within your remaining balance')
        expect(page.locator('#balance')).to_have_text('$488.00')
        page.locator('#amount').fill('0.10'); page.locator('#note').fill('<img src=x onerror=alert(1)>')
        page.get_by_role('button', name='Log purchase', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$487.90')
        assert not page.locator('#history img').count()
        with page.expect_download() as info:
            page.get_by_role('button', name='Export CSV').click()
        csv_path = info.value.path()
        assert 'Lunch at The Edge' in Path(csv_path).read_text()
        page.get_by_role('button', name='Remove <img src=x onerror=alert(1)> $0.10', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$488.00')
        expect(other.locator('#balance')).to_have_text('$488.00')
        page.locator('#reserve').fill('501')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#budget-status')).to_contain_text('reserve cannot exceed')
        expect(page.locator('#balance')).to_have_text('$488.00')
        page.locator('#reserve').fill('50')
        page.locator('#start').fill('2025-01-01'); page.locator('#end').fill('2025-01-10')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#daily')).to_have_text('$0.00')
        expect(page.locator('#pace')).to_contain_text('No weekdays remain')
        page.get_by_role('button', name='Remove Lunch at The Edge $12.00', exact=True).click()
        expect(page.locator('#balance')).to_have_text('$500.00')
        expect(other.locator('#balance')).to_have_text('$500.00')
        # Fri + Mon only: 2 weekdays; reserve $50 leaves $225/day.
        page.locator('#start').fill('2099-01-02'); page.locator('#end').fill('2099-01-05')
        page.get_by_role('button', name='Save budget', exact=True).click()
        expect(page.locator('#daily')).to_have_text('$225.00')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Horizontal overflow'
        page.locator('h1').click()
        page.screenshot(path=str(ARTIFACTS / f'{label}-wait-budget.png'), full_page=True)
        assert not errors, errors
        print(f'PASS {label}: scan scenarios, boundaries, forecast, budget, cents, persistence, cross-tab sync, invalid amounts, history removal, CSV, input safety, dates, responsive layout')
        context.close()
    context = browser.new_context()
    context.add_init_script("Object.defineProperty(window, 'localStorage', {get() {throw new Error('blocked')}})")
    page = context.new_page(); page.goto(BASE)
    page.get_by_role('button', name='Save budget', exact=True).click()
    expect(page.locator('#budget-status')).to_contain_text('will be lost after a refresh')
    expect(page.locator('#balance')).to_have_text('$500.00')
    page.locator('#amount').fill('5'); page.get_by_role('button', name='Log purchase', exact=True).click()
    expect(page.locator('#balance')).to_have_text('$495.00')
    print('PASS storage-unavailable fallback')
    context.close()
    context = browser.new_context()
    page = context.new_page(); page.goto(BASE)
    page.evaluate("localStorage.setItem('better-lunch-budget-v2', '{invalid')")
    page.reload(); expect(page.locator('#budget-status')).to_contain_text('could not be read')
    page.keyboard.press('Tab'); expect(page.locator('.skip')).to_be_focused()
    page.keyboard.press('Enter')
    print('PASS corrupt storage recovery and keyboard skip link')
    print('Browser:', browser.version)
    browser.close()
